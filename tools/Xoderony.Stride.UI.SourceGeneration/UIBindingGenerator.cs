using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Text;
using YamlDotNet.Core;

namespace Xoderony.Stride.UI.SourceGeneration;

[Generator]
public sealed class UIBindingGenerator : IIncrementalGenerator {
    private static readonly DiagnosticDescriptor InvalidConfiguration = Descriptor("XSUI001", "Invalid UI binding configuration");
    private static readonly DiagnosticDescriptor InvalidAsset = Descriptor("XSUI002", "Invalid or unsupported UI asset");
    private static readonly DiagnosticDescriptor InvalidName = Descriptor("XSUI003", "Invalid or duplicate UI name");
    private static readonly DiagnosticDescriptor InvalidType = Descriptor("XSUI004", "Unresolved UI element type");

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var files = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".sduilib", StringComparison.OrdinalIgnoreCase))
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (pair, token) => {
                pair.Right.GlobalOptions.TryGetValue("build_property.RootNamespace", out var rootNamespace);
                pair.Right.GlobalOptions.TryGetValue("build_property.MSBuildProjectDirectory", out var projectDirectory);
                var defaultNamespace = DefaultNamespace(pair.Left.Path, projectDirectory, rootNamespace, out var invalidDirectory);
                return new Input(
                    pair.Left.Path,
                    pair.Left.GetText(token),
                    defaultNamespace,
                    Path.GetFileNameWithoutExtension(pair.Left.Path) + "Library",
                    invalidDirectory
                );
            }).Collect();
        context.RegisterSourceOutput(files.Combine(context.CompilationProvider), static (output, pair) => Generate(output, pair.Left, pair.Right));
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<Input> inputs, Compilation compilation) {
        var generated = new List<(Input Input, string Identity, string Source)>();
        var counts = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var input in inputs) {
            context.CancellationToken.ThrowIfCancellationRequested();
            try {
                if (input.InvalidDirectory is not null) {
                    throw new AssetException(3, $"Asset directory '{input.InvalidDirectory}' is not a C# identifier.");
                }

                if (!Identifier(input.TypeName) || input.TypeName == "Root") {
                    throw new AssetException(3, $"Invalid generated type name '{input.TypeName}'.");
                }

                foreach (var part in input.Namespace.Split('.')) {
                    if (!Identifier(part)) {
                        throw new AssetException(1, $"Invalid namespace '{input.Namespace}'.");
                    }
                }

                if (input.Text is null) {
                    throw new AssetException(2, "Unable to read the AdditionalFile.");
                }

                var asset = UIAssetReader.Read(input.Text.ToString(), context.CancellationToken);
                var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace ");
                source.Append(EscapeNamespace(input.Namespace)).Append(";\n")
                    .Append("[global::Stride.Core.DataContract]\n")
                    .Append("public readonly struct @").Append(input.TypeName).Append(" {\n")
                    .Append("    [global::Stride.Core.DataMember]\n")
                    .Append("    public global::Stride.Engine.UILibrary? Library { get; init; }\n");

                var scopes = new HashSet<string>(StringComparer.Ordinal);
                foreach (var root in asset.Roots) {
                    var typeName = root.Name + "View";
                    if (!Identifier(root.Name) || typeName == input.TypeName || !scopes.Add(typeName)) {
                        throw new AssetException(3, $"Library roots must have unique C# names; invalid root '{root.Name}'.");
                    }

                    EmitBinding(source, typeName, input.TypeName, asset, root, compilation, context);
                }

                source.Append("}\n");

                var identity = input.Namespace + "." + input.TypeName;
                counts.TryGetValue(identity, out var count);
                counts[identity] = count + 1;
                generated.Add((input, identity, source.ToString()));
            } catch (AssetException exception) {
                Report(context, input, exception.Diagnostic, exception.Message);
            } catch (YamlException exception) {
                Report(context, input, 2, exception.Message);
            }
        }

        foreach (var entry in generated) {
            if (counts[entry.Identity] > 1 || compilation.GetTypeByMetadataName(entry.Identity) is not null) {
                Report(context, entry.Input, 1, $"Multiple declarations generate '{entry.Identity}'.");
                continue;
            }

            context.AddSource(entry.Identity + ".g.cs", SourceText.From(entry.Source, Encoding.UTF8));
        }
    }

    private static void EmitBinding(StringBuilder source, string typeName, string libraryTypeName, Asset asset, Element root, Compilation compilation, SourceProductionContext context) {
        var members = new List<(Element Element, string Type)>();
        var names = new HashSet<string>(StringComparer.Ordinal) { typeName, "Root", "Equals", "GetHashCode", "GetType", "ToString", "ReferenceEquals", "MemberwiseClone", "Finalize" };

        var pending = new Stack<Element>();
        pending.Push(root);
        while (pending.Count > 0) {
            context.CancellationToken.ThrowIfCancellationRequested();
            var element = pending.Pop();
            if (element.Name.Length > 0) {
                if (!Identifier(element.Name) || !names.Add(element.Name)) {
                    throw new AssetException(3, $"Name '{element.Name}' is invalid, duplicated or reserved in '{typeName}'.");
                }

                members.Add((element, ResolveType(element.Tag, compilation)));
            }

            foreach (var edge in element.Children) {
                pending.Push(asset.Elements[edge.ChildId]);
            }
        }

        members.Sort(static (left, right) => StringComparer.Ordinal.Compare(left.Element.Name, right.Element.Name));
        var rootType = ResolveType(root.Tag, compilation);
        EmitLibraryBinding(source, typeName, libraryTypeName, asset, root, compilation, rootType, members);
    }

    private static void EmitLibraryBinding(StringBuilder source, string typeName, string libraryTypeName, Asset asset, Element root, Compilation compilation, string rootType, List<(Element Element, string Type)> members) {
        source.Append("    public @").Append(typeName).Append(" Create").Append(root.Name).Append("() {\n")
            .Append("        var library = Library;\n")
            .Append("        global::System.Diagnostics.Debug.Assert(library is not null, \"").Append(libraryTypeName).Append(" requires its configured UILibrary.\");\n")
            .Append("        var root = global::Stride.Engine.UILibraryExtensions.InstantiateElement<").Append(rootType).Append(">(library, \"").Append(root.Name).Append("\");\n")
            .Append("        global::System.Diagnostics.Debug.Assert(root is not null, \"").Append(libraryTypeName).Append(": export ").Append(root.Name).Append(" must exist as ").Append(rootType).Append(".\");\n")
            .Append("        return new @").Append(typeName).Append("(root);\n")
            .Append("    }\n")
            .Append("    public sealed class @").Append(typeName).Append(" {\n");
        EmitFieldsAndProperties(source, rootType, members, "        ");
        source.Append("        internal @").Append(typeName).Append("(").Append(rootType).Append(" root) {\n");
        EmitPathBindings(source, asset, root, compilation, members, "root", root.Name, "            ");
        source.Append("        }\n")
            .Append("    }\n");
    }

    private static void EmitFieldsAndProperties(StringBuilder source, string rootType, List<(Element Element, string Type)> members, string indentation) {
        source.Append(indentation).Append("private readonly ").Append(rootType).Append(" _root;\n");
        foreach (var member in members) {
            source.Append(indentation).Append("private readonly ").Append(member.Type).Append(" _").Append(member.Element.Name).Append(";\n");
        }

        source.Append(indentation).Append("public ").Append(rootType).Append(" Root => _root;\n");
        foreach (var member in members) {
            source.Append(indentation).Append("public ").Append(member.Type).Append(" @").Append(member.Element.Name).Append(" => _").Append(member.Element.Name).Append(";\n");
        }
    }

    private static void EmitPathBindings(StringBuilder source, Asset asset, Element root, Compilation compilation, List<(Element Element, string Type)> members, string rootVariable, string viewName, string indentation) {
        var variables = new Dictionary<Guid, string> { [root.Id] = rootVariable };
        var nextVariable = 0;
        EmitElementBinding(source, asset, root, compilation, rootVariable, "Root", viewName, variables, ref nextVariable, indentation);
        source.Append(indentation).Append("_root = ").Append(rootVariable).Append(";\n");
        foreach (var member in members) {
            source.Append(indentation).Append("_").Append(member.Element.Name).Append(" = ").Append(variables[member.Element.Id]).Append(";\n");
        }
    }

    private static void EmitElementBinding(StringBuilder source, Asset asset, Element element, Compilation compilation, string variable, string path, string viewName, Dictionary<Guid, string> variables, ref int nextVariable, string indentation) {
        EmitNameValidation(source, element, variable, path, viewName, indentation);
        foreach (var edge in element.Children) {
            var child = asset.Elements[edge.ChildId];
            if (!HasNamedDescendant(asset, child)) {
                continue;
            }

            EnsureRelationSupported(element, edge.Relation, compilation);
            var childType = ResolveType(child.Tag, compilation);
            var childVariable = "node" + nextVariable++;
            var childPath = edge.Relation == ChildRelation.Children ? path + ".Children[" + edge.Index + "]" : path + ".Content";
            EmitPathAccess(source, edge, variable, childVariable, childPath, childType, viewName, indentation);
            variables.Add(child.Id, childVariable);
            EmitElementBinding(source, asset, child, compilation, childVariable, childPath, viewName, variables, ref nextVariable, indentation);
        }
    }

    private static bool HasNamedDescendant(Asset asset, Element element) {
        if (element.Name.Length > 0) {
            return true;
        }

        foreach (var edge in element.Children) {
            if (HasNamedDescendant(asset, asset.Elements[edge.ChildId])) {
                return true;
            }
        }

        return false;
    }

    private static void EmitPathAccess(StringBuilder source, ChildEdge edge, string parentVariable, string variable, string path, string type, string viewName, string indentation) {
        if (edge.Relation == ChildRelation.Children) {
            source.Append(indentation).Append("global::System.Diagnostics.Debug.Assert(").Append(parentVariable).Append(".Children.Count > ").Append(edge.Index).Append(", \"").Append(viewName).Append(": ").Append(path).Append(" must exist.\");\n")
                .Append(indentation).Append("global::System.Diagnostics.Debug.Assert(").Append(parentVariable).Append(".Children[").Append(edge.Index).Append("] is ").Append(type).Append(", \"").Append(viewName).Append(": ").Append(path).Append(" must be ").Append(type).Append(".\");\n")
                .Append(indentation).Append("var ").Append(variable).Append(" = (").Append(type).Append(")").Append(parentVariable).Append(".Children[").Append(edge.Index).Append("];\n");
        } else {
            source.Append(indentation).Append("global::System.Diagnostics.Debug.Assert(").Append(parentVariable).Append(".Content is ").Append(type).Append(", \"").Append(viewName).Append(": ").Append(path).Append(" must be ").Append(type).Append(".\");\n")
                .Append(indentation).Append("var ").Append(variable).Append(" = (").Append(type).Append(")").Append(parentVariable).Append(".Content;\n");
        }
    }

    private static void EmitNameValidation(StringBuilder source, Element element, string variable, string path, string viewName, string indentation) {
        if (element.Name.Length == 0) {
            return;
        }

        var expectedName = SymbolDisplay.FormatLiteral(element.Name, true);
        source.Append(indentation).Append("global::System.Diagnostics.Debug.Assert(global::System.String.Equals(").Append(variable).Append(".Name, ").Append(expectedName).Append(", global::System.StringComparison.Ordinal), \"").Append(viewName).Append(": ").Append(path).Append(" must be named ").Append(element.Name).Append(".\");\n");
    }

    private static void EnsureRelationSupported(Element element, ChildRelation relation, Compilation compilation) {
        var requiredTypeName = relation == ChildRelation.Children ? "Stride.UI.Panels.Panel" : "Stride.UI.Controls.ContentControl";
        var requiredType = compilation.GetTypeByMetadataName(requiredTypeName);
        if (requiredType is null || !Inherits(ResolveTypeSymbol(element.Tag, compilation), requiredType)) {
            var relationName = relation == ChildRelation.Children ? "Children" : "Content";
            throw new AssetException(4, $"UI type '{element.Tag}' does not support {relationName} binding.");
        }
    }

    private static bool Inherits(INamedTypeSymbol type, INamedTypeSymbol baseType) {
        for (var current = type; current is not null; current = current.BaseType) {
            if (SymbolEqualityComparer.Default.Equals(current, baseType)) {
                return true;
            }
        }

        return false;
    }

    private static string ResolveType(string tag, Compilation compilation) {
        return ResolveTypeSymbol(tag, compilation).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }

    private static INamedTypeSymbol ResolveTypeSymbol(string tag, Compilation compilation) {
        var name = tag.StartsWith("!", StringComparison.Ordinal) ? tag.Substring(1) : tag;
        INamedTypeSymbol? resolved = null;
        foreach (var prefix in new[] { "", "Stride.UI.Controls.", "Stride.UI.Panels.", "Stride.UI." }) {
            var candidate = compilation.GetTypeByMetadataName(prefix + name);
            if (candidate is null) {
                continue;
            }

            var current = candidate;
            while (current is not null && current.ToDisplayString() != "Stride.UI.UIElement") {
                current = current.BaseType;
            }

            if (current is null || candidate.DeclaredAccessibility != Accessibility.Public || candidate.Arity != 0) {
                continue;
            }

            if (resolved is not null && !SymbolEqualityComparer.Default.Equals(candidate, resolved)) {
                throw new AssetException(4, $"Ambiguous UI type tag '{tag}'. Use a fully qualified type tag.");
            }

            resolved = candidate;
        }

        return resolved
            ?? throw new AssetException(4, $"Cannot resolve '{tag}' to a public UIElement type. Reference Stride.UI; custom aliases are unsupported, use a fully qualified CLR tag.");
    }

    private static bool Identifier(string value) {
        return value.Length > 0 && value[0] != '@'
            && (SyntaxFacts.IsValidIdentifier(value) || SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None)
            && SyntaxFactory.ParseToken("@" + value).ValueText == value;
    }

    private static string EscapeNamespace(string value) {
        return "@" + value.Replace(".", ".@");
    }

    private static string DefaultNamespace(string path, string? projectDirectory, string? rootNamespace, out string? invalidDirectory) {
        invalidDirectory = null;
        var result = rootNamespace is null || string.IsNullOrWhiteSpace(rootNamespace) ? "StrideUIBindings" : rootNamespace;
        var relativePath = path.Replace('\\', '/');
        if (projectDirectory is not null && projectDirectory.Length > 0) {
            var prefix = projectDirectory.Replace('\\', '/').TrimEnd('/') + "/";
            if (relativePath.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) {
                relativePath = relativePath.Substring(prefix.Length);
            }
        }

        if (relativePath.StartsWith("Assets/", StringComparison.OrdinalIgnoreCase)) {
            var directoryEnd = relativePath.LastIndexOf('/');
            if (directoryEnd > "Assets".Length) {
                var directories = relativePath.Substring("Assets/".Length, directoryEnd - "Assets/".Length).Split('/');
                foreach (var directory in directories) {
                    if (!Identifier(directory)) {
                        invalidDirectory = directory;
                        break;
                    }
                }

                result += "." + string.Join(".", directories);
            }
        }

        return result;
    }

    private static DiagnosticDescriptor Descriptor(string id, string title) {
        return new DiagnosticDescriptor(id, title, "{0}", "Xoderony.Stride.UI.SourceGeneration", DiagnosticSeverity.Error, true);
    }

    private static void Report(SourceProductionContext context, Input input, int diagnostic, string message) {
        var position = new LinePosition(0, 0);
        var location = Location.Create(input.Path, new TextSpan(0, 0), new LinePositionSpan(position, position));
        var descriptor = diagnostic switch { 1 => InvalidConfiguration, 3 => InvalidName, 4 => InvalidType, _ => InvalidAsset };
        context.ReportDiagnostic(Diagnostic.Create(descriptor, location, message));
    }

    private sealed class Input(string path, SourceText? text, string namespaceName, string typeName, string? invalidDirectory) {
        public string Path { get; } = path;
        public SourceText? Text { get; } = text;
        public string Namespace { get; } = namespaceName;
        public string TypeName { get; } = typeName;
        public string? InvalidDirectory { get; } = invalidDirectory;
    }
}
